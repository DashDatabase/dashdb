// Example schemas for the converter tools: one realistic schema per source format and theme.
// Each converts cleanly (no errors, and SQL output that runs; see convert.db.test.ts), so the
// first thing a visitor sees is a conversion that works. Lossy cases are explained in the tool
// pages instead of being shown off here.
import type { SourceFormat } from '../detect';

export interface ConvertExample {
  readonly format: SourceFormat;
  readonly source: string;
}

