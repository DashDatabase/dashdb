-- Multi-tenant SaaS: organizations, members, projects, API keys, audit log.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE member_role AS ENUM ('owner', 'admin', 'member', 'viewer');
CREATE TYPE plan_tier AS ENUM ('free', 'team', 'enterprise');

CREATE TABLE organizations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug varchar(63) NOT NULL UNIQUE,
  name text NOT NULL,
  plan plan_tier NOT NULL DEFAULT 'free',
  seats integer NOT NULL DEFAULT 5 CHECK (seats > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email varchar(320) NOT NULL,
  display_name text,
  is_staff boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE memberships (
  org_id uuid NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role member_role NOT NULL DEFAULT 'member',
  invited_by uuid REFERENCES users (id) ON DELETE SET NULL,
  joined_at timestamptz,
  PRIMARY KEY (org_id, user_id)
);

CREATE TABLE projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id uuid NOT NULL,
  name text NOT NULL,
  settings jsonb NOT NULL DEFAULT '{}'::jsonb,
  archived boolean NOT NULL DEFAULT false,
  CONSTRAINT projects_org_fkey FOREIGN KEY (org_id) REFERENCES organizations (id) ON DELETE CASCADE,
  CONSTRAINT projects_org_name_key UNIQUE (org_id, name)
);

CREATE TABLE api_keys (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid NOT NULL REFERENCES organizations ON DELETE CASCADE,
  prefix char(8) NOT NULL,
  hashed_secret bytea NOT NULL,
  scopes text[] NOT NULL DEFAULT '{}',
  last_used_at timestamptz,
  expires_at timestamptz,
  revoked_at timestamptz
);

CREATE TABLE audit_events (
  id bigserial PRIMARY KEY,
  org_id uuid NOT NULL REFERENCES organizations (id),
  actor_id uuid REFERENCES users (id),
  action varchar(64) NOT NULL,
  payload jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX organizations_active_idx ON organizations (created_at DESC) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX api_keys_prefix_idx ON api_keys (prefix) WHERE revoked_at IS NULL;
CREATE INDEX audit_events_org_time_idx ON audit_events (org_id, occurred_at DESC);
CREATE INDEX audit_events_payload_idx ON audit_events USING gin (payload);
CREATE INDEX memberships_user_idx ON memberships (user_id);

COMMENT ON TABLE organizations IS 'A tenant; every row in the app belongs to one';
COMMENT ON COLUMN api_keys.prefix IS 'First 8 characters, shown in the UI';
