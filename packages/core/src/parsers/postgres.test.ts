import { describe, expect, it } from 'vitest';
import { parsePostgresDDL } from './postgres';
import { MAX_INPUT_BYTES } from './types';

const parse = (sql: string) => parsePostgresDDL(sql, { createId: (hint) => hint });

describe('parsePostgresDDL', () => {
  it('rejects inputs over 2 MB without parsing', () => {
    const { schema, diagnostics } = parse(
      `-- ${'x'.repeat(MAX_INPUT_BYTES)}\nCREATE TABLE t (id int);`,
    );
    expect(schema.tables).toEqual([]);
    expect(diagnostics).toEqual([
      expect.objectContaining({ code: 'input-too-large', severity: 'error' }),
    ]);
  });

  it('reports a syntax error at its exact position and keeps parsing', () => {
    const { schema, diagnostics } = parse(
      'CREATE TABLE a (id int);\nCREATE TABLE b (\n  id int,,\n  name text\n);\nCREATE TABLE c (id int);',
    );
    expect(schema.tables.map((t) => t.name)).toEqual(['a', 'c']);
    expect(diagnostics).toEqual([
      {
        severity: 'error',
        code: 'syntax-error',
        message: 'CREATE TABLE b …: Syntax error near ","',
        line: 3,
        column: 10,
      },
    ]);
  });

  it('turns statements it does not model into warnings, never errors', () => {
    const { diagnostics } = parse(
      'GRANT SELECT ON t TO u;\nCREATE VIEW v AS SELECT 1;\nCREATE TRIGGER x BEFORE INSERT ON t FOR EACH ROW EXECUTE FUNCTION f();',
    );
    expect(diagnostics.map((d) => [d.severity, d.code, d.line])).toEqual([
      ['warning', 'unsupported-statement', 1],
      ['warning', 'unsupported-statement', 2],
      ['warning', 'unsupported-statement', 3],
    ]);
  });

  it('never throws on garbage input', () => {
    for (const input of [
      '',
      ';;;',
      '(((',
      "'unterminated",
      '$$ open',
      'CREATE TABLE',
      '\u0000\u0001',
    ]) {
      expect(() => parse(input)).not.toThrow();
    }
  });

  it('resolves REFERENCES without a column list to the target primary key', () => {
    const { schema, diagnostics } = parse(
      'CREATE TABLE child (parent_id int REFERENCES parent DEFERRABLE INITIALLY DEFERRED);\nCREATE TABLE parent (id int PRIMARY KEY);',
    );
    expect(diagnostics).toEqual([]);
    expect(schema.tables[0]?.foreignKeys[0]).toMatchObject({
      refTable: 'table:public.parent',
      refColumns: ['column:public.parent.id'],
    });
  });

  it('maps serial, identity and nextval defaults to auto-increment', () => {
    const { schema } = parse(`CREATE TABLE t (
      a serial, b bigserial, c int GENERATED ALWAYS AS IDENTITY,
      d int DEFAULT nextval('d_seq'), e int GENERATED ALWAYS AS (a * 2) STORED
    );`);
    expect(
      schema.tables[0]?.columns.map((c) => [
        c.name,
        c.nativeType,
        c.autoIncrement,
        c.default,
        c.metadata,
      ]),
    ).toEqual([
      ['a', 'integer', true, { kind: 'sequence', name: 't_a_seq' }, {}],
      ['b', 'bigint', true, { kind: 'sequence', name: 't_b_seq' }, {}],
      ['c', 'int', true, null, { identity: 'always' }],
      ['d', 'int', true, { kind: 'sequence', name: 'd_seq' }, {}],
      ['e', 'int', false, null, { generated: 'a * 2' }],
    ]);
  });

  it('classifies defaults as literal, expression or sequence', () => {
    const { schema } = parse(`CREATE TABLE t (
      a int DEFAULT -1, b numeric DEFAULT 1.5, c text DEFAULT 'x', d bool DEFAULT true,
      e text DEFAULT NULL, f status DEFAULT 'on'::status, g jsonb DEFAULT '{}'::jsonb,
      h timestamptz DEFAULT now() + interval '1 day'
    );`);
    expect(schema.tables[0]?.columns.map((c) => c.default)).toEqual([
      { kind: 'literal', value: -1 },
      { kind: 'literal', value: 1.5 },
      { kind: 'literal', value: 'x' },
      { kind: 'literal', value: true },
      { kind: 'literal', value: null },
      { kind: 'literal', value: 'on' },
      { kind: 'literal', value: '{}' },
      { kind: 'expression', sql: "now() + interval '1 day'" },
    ]);
  });

  it('applies ALTER TABLE changes and COMMENT ON', () => {
    const { schema, diagnostics } = parse(`CREATE TABLE t (id int, n int);
ALTER TABLE t ADD CONSTRAINT t_pkey PRIMARY KEY (id), ALTER COLUMN n SET NOT NULL;
ALTER TABLE t ALTER COLUMN n DROP NOT NULL, ALTER COLUMN n SET DEFAULT 1;
ALTER TABLE t ALTER COLUMN n DROP DEFAULT;
ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE t ALTER COLUMN n TYPE bigint;
ALTER TABLE t RENAME COLUMN n TO m;
ALTER TABLE t ALTER COLUMN ghost SET NOT NULL;
ALTER TABLE ghost ADD COLUMN x int;
COMMENT ON TABLE t IS 'T';
COMMENT ON COLUMN t.id IS 'Id';
COMMENT ON VIEW v IS 'nope';`);
    const t = schema.tables[0];
    expect(t?.primaryKey?.name).toBe('t_pkey');
    expect(t?.comment).toBe('T');
    expect(
      t?.columns.map((c) => [c.name, c.nullable, c.default, c.autoIncrement, c.comment]),
    ).toEqual([
      ['id', false, null, true, 'Id'],
      ['n', true, null, false, null],
    ]);
    expect(diagnostics.map((d) => `${d.line}:${d.code}`)).toEqual([
      '6:unsupported-statement',
      '7:unsupported-statement',
      '8:unresolved-reference',
      '9:unresolved-reference',
      '12:unsupported-statement',
    ]);
  });

  it('skips expression indexes and LIKE/INHERITS with warnings', () => {
    const { schema, diagnostics } = parse(`CREATE TABLE base (id int);
CREATE TABLE t (LIKE base, id int) INHERITS (base);
CREATE INDEX ON t (lower(id::text));
CREATE INDEX ON ghost (id);`);
    expect(schema.tables[1]?.indexes).toEqual([]);
    expect(diagnostics.map((d) => d.code)).toEqual([
      'unsupported-feature',
      'unsupported-feature',
      'unsupported-feature',
      'unresolved-reference',
    ]);
  });

  it('keeps precision in the native spelling of timestamp types and maps arrays to unknown', () => {
    const { schema } = parse('CREATE TABLE t (a timestamp(3) with time zone, b int[], c "Mood");');
    expect(schema.tables[0]?.columns.map((c) => [c.nativeType, c.logicalType.kind])).toEqual([
      ['timestamp(3) with time zone', 'timestamp'],
      ['int[]', 'unknown'],
      ['Mood', 'unknown'],
    ]);
  });

  it('parses CRLF input exactly like LF input', () => {
    const lf = 'CREATE TABLE t (\n  id int CHECK (\n    id > 0\n  )\n);\nCREATE TABL x;';
    expect(parse(lf.replace(/\n/g, '\r\n'))).toEqual(parse(lf));
  });
});
