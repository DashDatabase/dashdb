import type { DiffResult } from '../diff/types';
import type { Schema } from '../ir/types';
import { toDrizzle } from '../serializers/drizzle';
import { toPrisma } from '../serializers/prisma';
import { compactTimestamp, header, snakeName } from './header';
import { buildSql } from './sql';
import {
  MigrationError,
  type DrizzleJournal,
  type DrizzleOptions,
  type FrameworkOptions,
  type MigrationFile,
} from './types';

const PRISMA_PROVIDER: Record<string, string> = { postgres: 'postgresql', mysql: 'mysql' };
const DRIZZLE: Record<string, { dialect: DrizzleJournal['dialect']; version: string }> = {
  postgres: { dialect: 'postgresql', version: '7' },
  mysql: { dialect: 'mysql', version: '5' },
};

const BREAKPOINT = '\n--> statement-breakpoint\n';

function sqlFor(diff: DiffResult, ir: Schema, now: Date) {
  return buildSql(diff, ir.dialect, { now, embedded: true });
}

/** Lines shared by the headers of a framework migration's files. */
function counts(diff: DiffResult, irreversible: number, now: Date) {
  return { now, operations: diff.operations, warnings: diff.warnings.length, irreversible };
}

/**
 * A Prisma Migrate migration: the updated `schema.prisma`, and
 * `migrations/<timestamp>_<name>/migration.sql` with `migration_lock.toml`. Prisma has no down
 * migrations; the down SQL is written next to `migration.sql` as `down.sql` for manual
 * rollback, and Prisma ignores it.
 */
export function generatePrismaMigration(
  diff: DiffResult,
  ir: Schema,
  options: FrameworkOptions,
): MigrationFile[] {
  const provider = PRISMA_PROVIDER[ir.dialect];
  if (!provider) throw new MigrationError(`Prisma migrations are not supported for ${ir.dialect}`);
  const now = options.now ?? new Date();
  const sql = sqlFor(diff, ir, now);
  const folder = `prisma/migrations/${compactTimestamp(now)}_${snakeName(options.name)}`;
  const info = counts(diff, sql.irreversible, now);
  const note =
    'Prisma Migrate runs this file as one script: no CONCURRENTLY, and no explicit transaction.';
  return [
    { path: 'prisma/schema.prisma', contents: `${header('//', info)}\n\n${toPrisma(ir).code}` },
    {
      path: `${folder}/migration.sql`,
      contents: `${header('--', { ...info, notes: [note] })}\n\n${sql.bodies.up}\n`,
    },
    {
      path: `${folder}/down.sql`,
      contents: `${header('--', {
        ...info,
        operations: sql.downOperations,
        notes: ['Prisma Migrate has no down migrations: run this by hand to roll back.', note],
      })}\n\n${sql.bodies.down}\n`,
    },
    {
      path: 'prisma/migrations/migration_lock.toml',
      contents: `${header('#', info)}\nprovider = "${provider}"\n`,
    },
  ];
}

/**
 * A drizzle-kit migration: the updated `schema.ts`, `<NNNN>_<name>.sql` with statement
 * breakpoints, and `meta/_journal.json` with a new entry appended to `options.journal`.
 * Limitations (see README.md): no `meta/<NNNN>_snapshot.json` is written, drizzle-kit has no
 * down migrations (the down SQL is `<NNNN>_<name>.down.sql`, which the migrator ignores), and
 * the journal carries no header because JSON has no comments.
 */
export async function generateDrizzleMigration(
  diff: DiffResult,
  ir: Schema,
  options: DrizzleOptions,
): Promise<MigrationFile[]> {
  const kit = DRIZZLE[ir.dialect];
  if (!kit) throw new MigrationError(`Drizzle migrations are not supported for ${ir.dialect}`);
  const now = options.now ?? new Date();
  const sql = sqlFor(diff, ir, now);
  const previous = options.journal?.entries ?? [];
  const idx = previous.length;
  const tag = `${String(idx).padStart(4, '0')}_${snakeName(options.name)}`;
  const info = counts(diff, sql.irreversible, now);
  const notes = [
    'drizzle-kit runs every migration inside one transaction: no CONCURRENTLY, and enum values',
    'added here cannot be used until it has committed. Statements are split at breakpoints.',
  ];
  const statements = (list: typeof sql.statements) =>
    list.length
      ? list.map((s) => (s.comment ? `-- ${s.comment}\n${s.sql}` : s.sql)).join(BREAKPOINT)
      : '-- No changes.';
  const journal: DrizzleJournal = {
    version: kit.version,
    dialect: kit.dialect,
    entries: [
      ...previous,
      { idx, version: kit.version, when: now.getTime(), tag, breakpoints: true },
    ],
  };
  return [
    {
      path: 'drizzle/schema.ts',
      // toDrizzle starts with its own one-line notice; this header replaces it.
      contents: `${header('//', info)}\n${(await toDrizzle(ir)).code.replace(/^\/\/ Generated by DashDB[^\n]*\n/, '')}`,
    },
    {
      path: `drizzle/${tag}.sql`,
      contents: `${header('--', { ...info, notes })}\n\n${statements(sql.statements)}\n`,
    },
    {
      path: `drizzle/${tag}.down.sql`,
      contents: `${header('--', {
        ...info,
        operations: sql.downOperations,
        notes: ['drizzle-kit has no down migrations: run this by hand to roll back.', ...notes],
      })}\n\n${statements(sql.downStatements)}\n`,
    },
    { path: 'drizzle/meta/_journal.json', contents: `${JSON.stringify(journal, null, 2)}\n` },
  ];
}
