import { diffSchemas } from '../../diff/diff';
import type { DiffResult } from '../../diff/types';
import type { Schema } from '../../ir/types';
import { parseMySQLDDL, parsePostgresDDL } from '../../parsers';

export interface Scenario {
  readonly name: string;
  readonly before: Schema;
  readonly after: Schema;
  readonly diff: DiffResult;
  readonly beforeSql: string;
}

export const NOW = new Date('2026-10-30T12:00:00Z');

function scenario(
  name: string,
  parse: (sql: string) => Schema,
  beforeSql: string,
  afterSql: string,
  confirmedRenames: string[] = [],
): Scenario {
  const before = parse(beforeSql);
  const after = parse(afterSql);
  return { name, before, after, beforeSql, diff: diffSchemas(before, after, { confirmedRenames }) };
}

const pg = (sql: string) => parsePostgresDDL(sql).schema;
const my = (sql: string) => parseMySQLDDL(sql).schema;

/**
 * A blog that grows up: a confirmed table rename, serial → identity, a retyped and tightened
 * column, an enum that gains one value and an enum that loses one, a changed FK, a new table
 * with an FK and a check, a dropped table and column, a replaced index (built concurrently),
 * a new unique key and a table comment.
 */
export const postgresScenario = scenario(
  'grow_the_blog',
  pg,
  `CREATE TYPE status AS ENUM ('draft', 'paid', 'void');
CREATE TYPE visibility AS ENUM ('public', 'private');
CREATE TABLE users (id serial PRIMARY KEY, email text, name text, legacy text);
CREATE TABLE posts (
  id int PRIMARY KEY, user_id int REFERENCES users, s status DEFAULT 'draft',
  v visibility NOT NULL DEFAULT 'public', title text, slug text);
CREATE INDEX posts_title ON posts (title);
CREATE TABLE audit_log (id bigint PRIMARY KEY, note text);`,
  `CREATE TYPE status AS ENUM ('draft', 'open', 'paid');
CREATE TYPE visibility AS ENUM ('public', 'unlisted', 'private');
CREATE TABLE app_users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email varchar(255) NOT NULL, name text);
CREATE TABLE posts (
  id int PRIMARY KEY, user_id int REFERENCES app_users ON DELETE CASCADE, s status DEFAULT 'open',
  v visibility NOT NULL DEFAULT 'public', title text, slug text, body text,
  CONSTRAINT posts_slug_key UNIQUE (slug));
CREATE INDEX posts_title_body ON posts (title, body);
CREATE TABLE comments (
  id int PRIMARY KEY, post_id int NOT NULL REFERENCES posts ON DELETE CASCADE,
  body text NOT NULL CHECK (length(body) > 0));
COMMENT ON TABLE posts IS 'Blog posts';`,
  ['table:public.users=>public.app_users'],
);

/** The same story on MySQL: inline enums, merged MODIFY COLUMN statements, table options. */
export const mysqlScenario = scenario(
  'grow_the_shop',
  my,
  `CREATE TABLE customers (id int NOT NULL AUTO_INCREMENT PRIMARY KEY, email varchar(100), name text, legacy text) ENGINE=InnoDB;
CREATE TABLE orders (
  id int NOT NULL PRIMARY KEY, customer_id int, status enum('new','paid','void') DEFAULT 'new', total decimal(10,2),
  CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES customers (id)) ENGINE=InnoDB;
CREATE INDEX orders_total ON orders (total);
CREATE TABLE audit_log (id bigint NOT NULL PRIMARY KEY, note text) ENGINE=InnoDB;`,
  `CREATE TABLE clients (id int NOT NULL AUTO_INCREMENT PRIMARY KEY, email varchar(255) NOT NULL, name text) ENGINE=InnoDB;
CREATE TABLE orders (
  id int NOT NULL PRIMARY KEY, customer_id int, status enum('new','open','paid') NOT NULL DEFAULT 'open', total decimal(12,2),
  notes text COMMENT 'Internal',
  CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES clients (id) ON DELETE CASCADE) ENGINE=InnoDB COMMENT='Orders';
CREATE INDEX orders_total_status ON orders (total, status);
CREATE TABLE refunds (
  id int NOT NULL PRIMARY KEY, order_id int NOT NULL, amount decimal(12,2) NOT NULL,
  CONSTRAINT refunds_order_fk FOREIGN KEY (order_id) REFERENCES orders (id), CONSTRAINT refunds_amount_chk CHECK (amount > 0)) ENGINE=InnoDB;`,
  ['table:default.customers=>default.clients'],
);
