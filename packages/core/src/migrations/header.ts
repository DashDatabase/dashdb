import type { Operation } from '../diff/types';

export interface HeaderInfo {
  readonly now: Date;
  readonly operations: readonly Operation[];
  readonly warnings: number;
  readonly irreversible: number;
  /** Extra lines (dialect notes, limitations). */
  readonly notes?: readonly string[];
}

/** `addColumn 2, dropTable 1`: operation counts by kind, in first-seen order. */
export function summarize(operations: readonly Operation[]): string {
  const counts = new Map<string, number>();
  for (const op of operations) counts.set(op.kind, (counts.get(op.kind) ?? 0) + 1);
  return [...counts].map(([kind, n]) => `${kind} ${n}`).join(', ');
}

/** The DashDB header every generated file starts with, as `prefix`-style comment lines. */
export function header(prefix: string, info: HeaderInfo): string {
  const summary = summarize(info.operations);
  const lines = [
    `Generated by DashDB on ${info.now.toISOString()}. Do not edit by hand; regenerate instead.`,
    `Operations: ${info.operations.length}${summary ? ` (${summary})` : ''}`,
    `Warnings: ${info.warnings}`,
    `Irreversible: ${info.irreversible}`,
    ...(info.notes ?? []),
  ];
  return lines.map((line) => `${prefix} ${line}`).join('\n');
}

/** `Add users email!` → `add_users_email`, for file and folder names. */
export function snakeName(name: string): string {
  return (
    name
      .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '') || 'migration'
  );
}

/** `20261030120000`: the UTC timestamp Prisma uses in migration folder names. */
export function compactTimestamp(now: Date): string {
  return now.toISOString().replace(/\D/g, '').slice(0, 14);
}
