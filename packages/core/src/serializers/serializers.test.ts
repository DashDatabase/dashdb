import { describe, expect, it } from 'vitest';
import { parseDBML, parseMySQLDDL, parsePostgresDDL, parsePrisma } from '../parsers';
import { toDBML, toDrizzle, toMySQLDDL, toPostgresDDL, toPrisma } from '.';

const pg = (sql: string) => parsePostgresDDL(sql).schema;
const my = (sql: string) => parseMySQLDDL(sql).schema;

describe('toPostgresDDL', () => {
  it('orders schemas, enums, tables by dependency, then indexes, then foreign keys', () => {
    const { code } = toPostgresDDL(
      pg(`CREATE TABLE b (id int PRIMARY KEY, a_id int REFERENCES app.a);
CREATE TYPE mood AS ENUM ('ok');
CREATE TABLE app.a (id int PRIMARY KEY, m mood);
CREATE INDEX b_a_idx ON b (a_id);`),
    );
    const order = [
      'CREATE SCHEMA',
      'CREATE TYPE',
      'CREATE TABLE app.a',
      'CREATE TABLE b',
      'CREATE INDEX',
      'ALTER TABLE',
    ];
    const positions = order.map((s) => code.indexOf(s));
    expect(positions.every((p) => p >= 0)).toBe(true);
    expect([...positions].sort((x, y) => x - y)).toEqual(positions);
  });

  it('chooses serial, nextval or identity for auto-increment columns', () => {
    const { code } = toPostgresDDL(
      pg(
        `CREATE TABLE t (a serial, b int DEFAULT nextval('other_seq'), c bigint GENERATED ALWAYS AS IDENTITY, d int GENERATED BY DEFAULT AS IDENTITY);`,
      ),
    );
    expect(code).toContain('  a serial NOT NULL');
    expect(code).toContain("  b int DEFAULT nextval('other_seq'::regclass)");
    expect(code).toContain('  c bigint GENERATED ALWAYS AS IDENTITY NOT NULL');
    expect(code).toContain('  d int GENERATED BY DEFAULT AS IDENTITY NOT NULL');
  });

  it('quotes identifiers that need it and escapes comments', () => {
    const { code } = toPostgresDDL(
      pg(`CREATE TABLE "User" ("order" int, "Name" text);\nCOMMENT ON TABLE "User" IS 'It''s';`),
    );
    expect(code).toContain('CREATE TABLE "User" (\n  "order" int,\n  "Name" text\n);');
    expect(code).toContain(`COMMENT ON TABLE "User" IS 'It''s';`);
  });

  it('translates types and enums from another dialect through the logical type', () => {
    const { code, warnings } = toPostgresDDL(
      my(
        "CREATE TABLE t (a tinyint(1), b enum('x','y'), c int AUTO_INCREMENT PRIMARY KEY, d set('p'));",
      ),
    );
    expect(code).toContain('  a boolean');
    expect(code).toContain('  b t_b');
    // MySQL's unnamed database becomes Postgres' public schema.
    expect(code).not.toContain('"default"');
    expect(code).toContain('  c integer GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(warnings.map((w) => w.element)).toEqual(['default.t.d']);
  });
});

describe('toMySQLDDL', () => {
  it('qualifies named databases and writes table options from metadata', () => {
    const { code } = toMySQLDDL(
      my("USE shop; CREATE TABLE t (id int) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='x';"),
    );
    expect(code).toContain('CREATE DATABASE IF NOT EXISTS shop;');
    expect(code).toContain(") ENGINE=innodb DEFAULT CHARSET=utf8mb4 COMMENT='x';");
    expect(code).toContain('CREATE TABLE shop.t (');
  });

  it('drops what MySQL cannot express, with warnings', () => {
    const { code, warnings } = toMySQLDDL(
      pg(
        `CREATE TABLE t (id int DEFAULT nextval('s'), x int);\nCREATE INDEX t_x ON t (x NULLS FIRST) WHERE x > 0;`,
      ),
    );
    // A nextval() default means auto-increment, which MySQL expresses directly.
    expect(code).toContain('  id int AUTO_INCREMENT,');
    expect(code).toContain('CREATE INDEX t_x ON t (x);');
    expect(warnings.map((w) => w.message)).toEqual([
      'MySQL has no partial indexes; WHERE dropped',
      'MySQL has no NULLS FIRST/LAST; dropped',
    ]);
  });
});

describe('toPrisma', () => {
  it('names relations when ambiguous and makes unique foreign keys one-to-one', () => {
    const { code } = toPrisma(
      pg(`CREATE TABLE users (id int PRIMARY KEY, manager_id int REFERENCES users);
CREATE TABLE profiles (id int PRIMARY KEY, user_id int UNIQUE NOT NULL REFERENCES users ON DELETE CASCADE);
CREATE TABLE transfers (id int PRIMARY KEY, from_id int NOT NULL REFERENCES users, to_id int NOT NULL REFERENCES users);`),
    );
    expect(code).toMatch(
      /manager\s+User\?\s+@relation\("UserManager", fields: \[managerId\], references: \[id\], onDelete: NoAction, onUpdate: NoAction\)/,
    );
    expect(code).toMatch(/usersManager\s+User\[\]\s+@relation\("UserManager"\)/);
    expect(code).toMatch(/profile\s+Profile\?\n/);
    expect(code).toMatch(
      /user\s+User\s+@relation\(fields: \[userId\], references: \[id\], onDelete: Cascade, onUpdate: NoAction\)/,
    );
    expect(code).toMatch(/from\s+User\s+@relation\("TransferFrom"/);
    expect(code).toMatch(/transfersFrom\s+Transfer\[\]\s+@relation\("TransferFrom"\)/);
    expect(code).toMatch(/transfersTo\s+Transfer\[\]\s+@relation\("TransferTo"\)/);
    // `int` is an alias of Prisma's default Int type, so no @db attribute is needed.
    expect(code).not.toContain('@db.Integer');
    expect(parsePrisma(code).diagnostics).toEqual([]);
  });

  it('ignores tables without a unique identifier, like prisma db pull', () => {
    const { code, warnings } = toPrisma(pg('CREATE TABLE log (msg text);'));
    expect(code).toContain('/// The underlying table does not contain a valid unique identifier');
    expect(code).toContain('  @@ignore');
    expect(warnings[0]?.message).toMatch(/@@ignore/);
  });

  it('maps enum values that are not identifiers and uses them as defaults', () => {
    const { code } = toPrisma(
      pg(
        `CREATE TYPE region AS ENUM ('us-east', '1st', 'ok');\nCREATE TABLE t (id int PRIMARY KEY, r region DEFAULT 'us-east');`,
      ),
    );
    expect(code).toContain(
      'enum Region {\n  us_east @map("us-east")\n  v1st    @map("1st")\n  ok\n\n  @@map("region")\n}',
    );
    expect(code).toContain('r  Region? @default(us_east)');
  });

  it('writes literals that do not fit the field type through dbgenerated()', () => {
    const { code, warnings } = toPrisma(
      my(
        "CREATE TABLE t (id int PRIMARY KEY, d datetime DEFAULT '0000-00-00 00:00:00', n int DEFAULT NULL);",
      ),
    );
    expect(code).toContain(`@default(dbgenerated("'0000-00-00 00:00:00'"))`);
    expect(code).toContain('@default(dbgenerated("NULL"))');
    expect(warnings.map((w) => w.code)).toContain('lossy-type');
  });
});

describe('toDrizzle', () => {
  it('avoids reserved identifiers and declares custom types once', async () => {
    const { code } = await toDrizzle(
      pg('CREATE TABLE "default" (id int PRIMARY KEY, a point, b point);'),
    );
    expect(code).toContain("export const default2 = pgTable('default'");
    expect(code.match(/const pointType = customType/g)).toHaveLength(1);
  });

  it('writes mysql enums inline and unsigned integers as options', async () => {
    const { code } = await toDrizzle(
      my(
        "CREATE TABLE t (id int unsigned PRIMARY KEY AUTO_INCREMENT, s enum('a','b') DEFAULT 'a');",
      ),
    );
    expect(code).toContain("id: int('id', { unsigned: true }).primaryKey().autoincrement()");
    expect(code).toContain("s: mysqlEnum('s', ['a', 'b']).default('a')");
  });
});

describe('toDBML', () => {
  it('writes composite and named keys in an indexes block', () => {
    const { code, warnings } = toDBML(
      pg(
        'CREATE TABLE t (a int, b int, CONSTRAINT t_pk PRIMARY KEY (a, b), CONSTRAINT custom_uq UNIQUE (b));',
      ),
    );
    expect(code).toContain("(a, b) [pk, name: 't_pk']");
    expect(code).toContain("b [unique, name: 'custom_uq']");
    expect(warnings.map((w) => w.message)).toEqual([
      'DBML has no named unique constraints; written as a unique index',
    ]);
    expect(parseDBML(code).diagnostics).toEqual([]);
  });

  it('quotes names and types that are not plain identifiers', () => {
    const { code } = toDBML(pg(`CREATE TABLE "my table" ("my col" double precision DEFAULT 1.5);`));
    expect(code).toContain('Table "my table" {\n  "my col" "double precision" [default: 1.5]\n}');
  });
});
