import { describe, expect, it } from 'vitest';
import { buildShowcase } from './migration-showcase';

describe('migration showcase', () => {
  it('is generated by the real engine, with the warnings the page describes', () => {
    const { up, report } = buildShowcase();
    expect(up).toContain('ALTER TABLE users ALTER COLUMN name TYPE varchar(80)');
    expect(up).toContain('CREATE INDEX CONCURRENTLY users_email_idx ON users (email);');
    expect(up).not.toContain('Generated by');
    expect(report.riskLevel).toBe('dangerous');
    expect(report.findings.map((f) => f.ruleId).sort()).toEqual([
      'alter-type-rewrite',
      'set-not-null-scan',
    ]);
  });

  it('is stable from build to build', () => {
    expect(buildShowcase()).toEqual(buildShowcase());
  });
});
