import { analyzeMigration, diffSchemas, generateSQL, parsePostgresDDL } from '@dashdb/core';
import Link from 'next/link';

// Server-only: the diff, SQL and safety review below run at build time through @dashdb/core,
// the same engine as the editor, and reach the browser as plain HTML.

export const SHOWCASE_BEFORE = `CREATE TABLE users (
  id    bigint PRIMARY KEY,
  email text NOT NULL,
  name  text
);`;

export const SHOWCASE_AFTER = `CREATE TABLE users (
  id    bigint PRIMARY KEY,
  email text NOT NULL,
  name  varchar(80) NOT NULL,
  plan  text NOT NULL DEFAULT 'free'
);
CREATE INDEX users_email_idx ON users (email);`;

/** Rows assumed for the review, so size-dependent rules apply as they would in production. */
const SHOWCASE_ROWS = 4_000_000;

export function buildShowcase() {
  // Readable, stable ids keep the output identical from build to build.
  const parse = (sql: string) => parsePostgresDDL(sql, { createId: (hint) => hint }).schema;
  const diff = diffSchemas(parse(SHOWCASE_BEFORE), parse(SHOWCASE_AFTER));
  const sql = generateSQL(diff, 'postgres', { now: new Date('2026-01-01T00:00:00Z') });
  const report = analyzeMigration(diff, 'postgres', { tableSizes: { users: SHOWCASE_ROWS } });
  // The file header (generator banner, counts) is noise in a showcase; keep the statements.
  const up = sql.up
    .split('\n')
    .filter(
      (line) => !/^-- (Generated by|Operations:|Warnings:|Irreversible:|Direction:)/.test(line),
    )
    .join('\n')
    .trim();
  return { up, report };
}

const SEVERITY_STYLE = {
  dangerous: 'border-danger/40 bg-danger/10 text-danger-text',
  caution: 'border-warning/40 bg-warning/10 text-warning-text',
  info: 'border-border bg-surface text-text-muted',
} as const;

function CodeBlock({ title, code, label }: { title: string; code: string; label: string }) {
  return (
    <figure className="min-w-0 overflow-hidden rounded-lg border bg-surface">
      <figcaption className="border-b px-4 py-2 text-xs font-medium text-text-muted">
        {title}
      </figcaption>
      <pre
        tabIndex={0}
        aria-label={label}
        className="overflow-x-auto p-4 font-mono text-[13px] leading-6 focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none"
      >
        <code>{code}</code>
      </pre>
    </figure>
  );
}

export function MigrationShowcase() {
  const { up, report } = buildShowcase();
  return (
    <div className="space-y-6" data-testid="migration-showcase">
      <div className="grid gap-4 lg:grid-cols-2">
        <CodeBlock title="Before" code={SHOWCASE_BEFORE} label="Schema before the change" />
        <CodeBlock
          title="After (edited on the canvas)"
          code={SHOWCASE_AFTER}
          label="Schema after the change"
        />
      </div>
      <div className="grid gap-4 lg:grid-cols-5">
        <div className="min-w-0 lg:col-span-3">
          <CodeBlock
            title="Generated migration · up.sql"
            code={up}
            label="Generated migration SQL"
          />
        </div>
        <div className="space-y-3 lg:col-span-2">
          <p className="text-sm text-text-muted">
            Safety review, assuming <code className="font-mono">users</code> holds{' '}
            {SHOWCASE_ROWS.toLocaleString('en-US')} rows:
          </p>
          <ul className="space-y-3">
            {report.findings.map((finding) => (
              <li
                key={`${finding.ruleId}-${finding.operationId}`}
                className={`rounded-lg border p-4 ${SEVERITY_STYLE[finding.severity]}`}
                data-testid="showcase-finding"
              >
                <p className="text-xs font-semibold tracking-wide uppercase">{finding.severity}</p>
                <p className="mt-1 font-medium text-text">{finding.title}</p>
                <p className="mt-1 text-sm text-text-muted">{finding.explanation}</p>
                <Link
                  href={finding.docsUrl}
                  className="mt-2 inline-block text-sm text-primary-text underline"
                >
                  The safer way
                </Link>
              </li>
            ))}
          </ul>
          <p className="text-sm text-text-muted">
            Note the index: DashDB builds it <code className="font-mono">CONCURRENTLY</code>,
            outside the transaction, so writes keep flowing.
          </p>
        </div>
      </div>
    </div>
  );
}
