import { rules } from '@dashdb/core';
import { describe, expect, it } from 'vitest';
import { buildGuideExample, GUIDE_EXAMPLES } from './examples';

describe('guide examples', () => {
  it('has an example for every rule and dialect, and each one triggers its rule', () => {
    for (const rule of rules) {
      for (const dialect of rule.dialects) {
        const built = buildGuideExample(rule.id, dialect);
        expect(built, `${dialect}/${rule.id}`).not.toBeNull();
        expect(built?.finding.ruleId).toBe(rule.id);
        expect(built?.finding.docsUrl).toBe(`/guides/${dialect}/${rule.id}`);
        expect(built?.up, `${dialect}/${rule.id}`).not.toBe('');
        expect(built?.up).not.toContain('Generated by');
      }
    }
  });

  it('has no examples for rules or dialects that do not exist', () => {
    for (const [ruleId, byDialect] of Object.entries(GUIDE_EXAMPLES)) {
      const rule = rules.find((r) => r.id === ruleId);
      expect(rule, ruleId).toBeDefined();
      for (const dialect of Object.keys(byDialect)) {
        expect(rule?.dialects, `${dialect}/${ruleId}`).toContain(dialect);
      }
    }
  });

  it('is stable from build to build', () => {
    expect(buildGuideExample('rename-breaks-app', 'mysql')).toEqual(
      buildGuideExample('rename-breaks-app', 'mysql'),
    );
  });
});
