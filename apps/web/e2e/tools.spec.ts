import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';

const TOOLS = [
  { slug: 'sql-to-prisma', output: 'enum MemberRole' },
  { slug: 'prisma-to-sql', output: 'CREATE TABLE posts' },
  { slug: 'postgres-to-mysql', output: 'AUTO_INCREMENT' },
  { slug: 'mysql-to-postgres', output: 'GENERATED BY DEFAULT AS IDENTITY' },
  { slug: 'sql-to-drizzle', output: 'pgTable(' },
  { slug: 'prisma-to-drizzle', output: "pgEnum('Status'" },
  { slug: 'dbml-to-sql', output: 'CREATE TYPE order_status' },
  { slug: 'sql-to-dbml', output: 'Table venues {' },
  { slug: 'sql-to-mermaid', output: 'erDiagram' },
  { slug: 'prisma-to-erd', output: 'erDiagram' },
] as const;

const converter = (page: Page) => page.getByTestId('tool-converter');

/** Waits for a finished conversion and Monaco in both panes. */
async function ready(page: Page) {
  await expect(converter(page)).toHaveAttribute('data-state', 'done', { timeout: 30_000 });
  await expect(page.locator('.monaco-editor')).toHaveCount(2, { timeout: 30_000 });
}

/**
 * The output pane's visible text, with Monaco's non-breaking spaces made plain. Monaco only
 * renders the lines in view, so expected snippets come from the top of each output.
 */
const outputText = (page: Page) =>
  page.evaluate(() =>
    (document.querySelector('[data-testid="tool-output"] .view-lines')?.textContent ?? '').replace(
      /\s+/g,
      ' ',
    ),
  );

test.describe('converter tools', () => {
  test('the hub lists every tool by category', async ({ page }) => {
    await page.goto('/tools');
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Free schema converters');
    for (const category of ['SQL and ORMs', 'Between databases', 'DBML', 'Diagrams']) {
      await expect(page.getByRole('heading', { level: 2, name: category })).toBeVisible();
    }
    for (const { slug } of TOOLS) {
      await expect(page.locator(`a[href="/tools/${slug}"]`)).toHaveCount(1);
    }
  });

  for (const { slug, output } of TOOLS) {
    test(`${slug} converts its example in the browser`, async ({ page }) => {
      await page.goto(`/tools/${slug}`);
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
      await ready(page);
      await expect(page.getByTestId('tool-status')).toContainText('in your browser');
      await expect.poll(() => outputText(page)).toContain(output);
      // Unique metadata and structured data on every page.
      await expect(page).toHaveTitle(/ · DashDB$/);
      const types = await page
        .locator('script[type="application/ld+json"]')
        .evaluateAll((nodes) =>
          nodes.map((n) => (JSON.parse(n.textContent) as { '@type': string })['@type']),
        );
      expect(types.sort()).toEqual(['BreadcrumbList', 'FAQPage']);
      await expect(page.getByTestId('mapping-table').locator('tbody tr').first()).toBeVisible();
    });
  }

  test('pages have distinct titles and descriptions', async ({ page }) => {
    const seen = new Set<string>();
    for (const { slug } of TOOLS) {
      await page.goto(`/tools/${slug}`);
      const title = await page.title();
      const description = await page.locator('meta[name="description"]').getAttribute('content');
      expect(seen.has(title), title).toBe(false);
      expect(seen.has(description ?? ''), slug).toBe(false);
      seen.add(title);
      seen.add(description ?? '');
    }
  });

  test('converting makes no server requests', async ({ page }) => {
    await page.goto('/tools/sql-to-prisma');
    await ready(page);
    await page.waitForLoadState('networkidle');
    const requests: string[] = [];
    page.on('request', (request) => {
      const url = new URL(request.url());
      // Static chunks (none are expected) and dev-server HMR are not conversions.
      if (
        url.pathname.startsWith('/_next/static/') ||
        url.pathname.startsWith('/_next/webpack-hmr')
      )
        return;
      requests.push(`${request.method()} ${request.url()}`);
    });
    // Replace the input: select all, then type a new schema.
    await page
      .getByTestId('tool-input')
      .locator('.monaco-editor textarea, .monaco-editor .native-edit-context')
      .first()
      .focus();
    await page.keyboard.press('ControlOrMeta+a');
    await page.keyboard.insertText(
      'CREATE TABLE invoices (id serial PRIMARY KEY, total numeric(10,2) NOT NULL);',
    );
    await expect.poll(() => outputText(page)).toContain('model Invoice');
    expect(requests).toEqual([]);
  });

  test('shows errors and no output for input that does not parse', async ({ page }) => {
    await page.goto('/tools/prisma-to-sql');
    await ready(page);
    await page
      .getByTestId('tool-input')
      .locator('.monaco-editor textarea, .monaco-editor .native-edit-context')
      .first()
      .focus();
    await page.keyboard.press('ControlOrMeta+a');
    await page.keyboard.insertText('model User {');
    await expect(page.getByTestId('tool-problems')).toContainText('Error');
    await expect(page.getByTestId('tool-status')).toHaveText(
      'Fix the errors below to see the result.',
    );
    await expect(page.getByRole('button', { name: 'Open in DashDB editor' })).toBeDisabled();
  });

  test('copies and downloads the output', async ({ page, context }) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write']);
    await page.goto('/tools/sql-to-dbml');
    await ready(page);
    await page.getByRole('button', { name: 'Copy' }).click();
    await expect(page.getByText('DBML copied to the clipboard.')).toBeVisible();
    expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('Table venues {');
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download' }).click();
    expect((await download).suggestedFilename()).toBe('schema.dbml');
  });

  test('draws the Prisma ERD and offers it as SVG', async ({ page }) => {
    await page.goto('/tools/prisma-to-erd');
    await ready(page);
    await expect(page.getByTestId('tool-diagram').getByRole('img')).toBeVisible({
      timeout: 30_000,
    });
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download SVG' }).click();
    expect((await download).suggestedFilename()).toBe('schema-diagram.svg');
    await page.getByRole('tab', { name: 'Mermaid' }).click();
    await expect.poll(() => outputText(page)).toContain('erDiagram');
  });

  test('opens the converted schema as a local project', async ({ page }) => {
    await page.goto('/tools/sql-to-prisma');
    await ready(page);
    await page.getByRole('button', { name: 'Open in DashDB editor' }).click();
    await page.waitForURL(/\/app\/p\/[\w-]+$/);
    await expect(page.getByTestId('table-count')).toHaveText('3 tables');
  });

  test('pass axe (WCAG 2.2 AA)', async ({ page }) => {
    for (const path of ['/tools', '/tools/mysql-to-postgres', '/tools/prisma-to-erd']) {
      await page.goto(path);
      if (path !== '/tools') await ready(page);
      const results = await new AxeBuilder({ page })
        .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'])
        // Monaco's own editor markup is third-party and checked by its maintainers.
        .exclude('.monaco-editor')
        .analyze();
      expect(results.violations, path).toEqual([]);
    }
  });
});
